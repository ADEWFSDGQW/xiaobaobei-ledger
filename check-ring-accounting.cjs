const assert = require('node:assert/strict');
const { fresh, empty, settle } = require('./dist/assets/ring-project.js');
const { derive, mergeDaily, localDay } = require('./dist/assets/ring-accounting.js');
const settings = { ratio: 3000, discount: 100 };
const date = localDay(new Date());
const state = empty();
state.drafts.pet.costs.push({ name: '60武器', price: 20, score: 2 });
state.drafts.pet.extra = 5;
state.drafts.pet.rewards.push({ kind: '书', name: '剑', level: '140', price: 100, quantity: 1 }, { kind: '修炼果', name: '修炼果', level: '', price: 80, quantity: 2 });
const saved = settle(state, 'pet');
const base = [{ date, goldIncome: 50, itemIncome: 10, cardCost: 5, netIncome: 55, convertedIncome: 55, conversionFactor: 1 }];
let days = derive(state.history);
assert.equal(days[date].revenue, 260);
assert.equal(days[date].cost, 35);
assert.equal(days[date].rows.length, 3);
let merged = mergeDaily(base, days, settings);
assert.equal(merged[0].netIncome, 280);
assert.equal(merged[0].itemIncome, 270);
assert.equal(merged[0].convertedIncome, 280);
assert.deepEqual(mergeDaily(merged, days, settings), merged, 'Repeated merge must not double count');
assert.equal(base[0].netIncome, 55, 'Ordinary ledger remains unchanged');
state.drafts.pet = JSON.parse(JSON.stringify(saved));
state.drafts.pet.rewards[0].price = 150;
settle(state, 'pet');
assert.equal(state.history.length, 1);
assert.equal(mergeDaily(base, derive(state.history), settings)[0].netIncome, 330);
state.drafts.human = fresh('human');
state.drafts.human.costs.push({ name: '70装备', price: 10, score: 0 });
state.drafts.human.rewards.push({ kind: '灵饰铁', name: '元灵晶石', level: '120', price: 60, quantity: 1 }, { kind: '战魄', name: '战魄', level: '', price: 20, quantity: 1 });
settle(state, 'human');
days = derive(state.history);
assert.equal(days[date].count, 2);
assert.equal(days[date].cost, 55);
assert.equal(mergeDaily(base, days, settings)[0].netIncome, 390);
const historical = { ...saved, id: 'old', endedAt: '2026-09-20T04:00:00Z' };
assert.equal(mergeDaily([], derive([historical]), settings)[0].date, '2026-09-20');
const loss = { ...historical, id: 'loss', rewards: [] };
assert.equal(mergeDaily([], derive([loss]), settings)[0].netIncome, -35);
assert.equal(mergeDaily(base, {}, settings)[0].netIncome, 55, 'Drafts do not enter totals');
assert.throws(() => derive([saved, saved]), /重复/);
console.log('PASS: unified ledger, pet/human rewards, fixed fee, other expenses, historical dates, loss, edits, precision and duplicate prevention.');
