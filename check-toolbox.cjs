const assert=require('node:assert/strict');
const core=require('./dist/assets/toolbox-core');
const guides=require('./dist/assets/toolbox-guides');
const {createScheduler,installToolboxTimers}=require('./electron/toolbox-timers');
const roles=Array.from({length:5},(_,i)=>({name:'角色'+i,target:'修炼',experience:100,balance:20,money:0.1,contribution:0}));
const data={version:1,entries:guides,tables:[],roles};
assert.equal(core.validate(data),data);
assert.equal(new Set(guides.map(g=>g.category)).size,3);
assert.throws(()=>core.validate({...data,entries:[guides[0],guides[0]]}),/条目/);
assert.throws(()=>core.validate({...data,roles:[roles[0]]}),/五个/);
assert.throws(()=>core.validate({...data,roles:roles.map((r,i)=>i? r:{...r,money:-1})}));
assert.throws(()=>core.validate({version:2,entries:[],tables:[]}));
assert.throws(()=>core.number('', '金额'));
assert.throws(()=>core.number(Infinity,'金额'));
let callback,closed=[],cleared=0;
const scheduler=createScheduler({closeWindow:async r=>{closed.push(r.pid);return '已请求正常关闭';},now:()=>1000,setTimer:f=>{callback=f;return 1;},clearTimer:()=>cleared++});
const row={pid:123,path:'C:\\test\\game.exe',start:'time',title:'测试窗口'};
assert.throws(()=>scheduler.schedule([row],0));
assert.throws(()=>scheduler.schedule([{...row,pid:'1;exit'}],1));
const handlers={};const sender={};
installToolboxTimers({app:{on(){}},ipcMain:{handle:(k,f)=>handlers[k]=f},dialog:{},getWindow:()=>({webContents:sender})});
assert.throws(()=>handlers['toolbox-game-status']({sender:{}}),/无效/);
assert.equal(handlers['toolbox-game-status']({sender}).active,false);
(async()=>{
  scheduler.schedule([row],1);assert.equal(scheduler.status().end,61000);
  const canceled=callback;scheduler.cancel();await canceled();assert.deepEqual(closed,[]);
  scheduler.schedule([row],1);await callback();assert.deepEqual(closed,[123]);assert.equal(scheduler.status().active,false);
  scheduler.schedule([row],1);scheduler.schedule([{...row,pid:124}],2);assert(cleared>=2);await callback();assert.deepEqual(closed,[123,124]);
  console.log('PASS: guide/backup validation, budget constraints, timer cancellation/replacement, selected-window execution and IPC sender checks.');
})().catch(e=>{console.error(e);process.exitCode=1;});
